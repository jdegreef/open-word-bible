"""List every rendering decision marked uncertain in one language, for reviewers.

    python3 scripts/review_checklist.py fr                 print the list
    python3 scripts/review_checklist.py fr --write         write docs/review-notes/fr-uncertain.md

The list follows the canonical book order of data/books.json, with each
book's chapters and verses in order. Each item links to the verse on the
site and gives the levels, the category, the choice and the drafter's
reason, so a reviewer can tick it off. Regenerate it after review work:
decisions that are no longer uncertain drop out.
"""
import argparse
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://openwordbible.org"
REASON_MAX = 300


def ref_key(ref):
    """(chapter, verse) of "GEN.1.14"."""
    _, chapter, verse = ref.split(".")
    return int(chapter), int(verse)


def short(text, limit=REASON_MAX):
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[:limit].rsplit(" ", 1)[0] + " …"


def items(lang):
    """(book, [(ref, levels, category, choice, reason), ...]) in canonical order."""
    books = json.load(open(os.path.join(ROOT, "data", "books.json"), encoding="utf-8"))["books"]
    for book in books:
        found = []
        for path in glob.glob(os.path.join(ROOT, "content", book, "*.json")):
            for record in json.load(open(path, encoding="utf-8"))["records"]:
                for d in record["decisions"]:
                    if d.get("language") == lang and d.get("uncertain"):
                        found.append((record["refs"][0], d.get("levels") or [], d["category"],
                                      d["choice"], d["reason"]))
        if found:
            found.sort(key=lambda item: ref_key(item[0]))
            yield book, found


def render(lang):
    books = json.load(open(os.path.join(ROOT, "data", "books.json"), encoding="utf-8"))["books"]
    groups = list(items(lang))
    total = sum(len(found) for _, found in groups)
    out = [f"# Uncertain rendering decisions: {lang}", "",
           f"Generated by `python3 scripts/review_checklist.py {lang} --write`; do not edit by hand. "
           f"{total} decisions in {len(groups)} books, every {lang} rendering decision the "
           "drafters marked uncertain. Tick an item once a reviewer has settled it, and "
           "regenerate the list after the content changes.", ""]
    for book, found in groups:
        out += [f"## {books[book].get(lang) or books[book]['en']} ({len(found)})", ""]
        for ref, levels, category, choice, reason in found:
            _, chapter, verse = ref.split(".")
            link = f"{SITE}/{lang}/{book.lower()}/{chapter}/#v{verse}"
            where = "/".join(levels) or "-"
            out.append(f"- [ ] [{book} {chapter}:{verse}]({link}) {where} · {category} · "
                       f"{short(choice, 160)} — {short(reason)}")
        out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("lang")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    text = render(args.lang)
    if args.write:
        path = os.path.join(ROOT, "docs", "review-notes", f"{args.lang}-uncertain.md")
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print(path)
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
